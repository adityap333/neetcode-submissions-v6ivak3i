your_dict = { 
  "a": 10, 
  "apple": 12,
  "bat": 7
}

# 1. Print dictionary itself
print(your_dict)

# 2. Print value of key "a"
print(your_dict["a"])

# 3. Check whether key "d" exists
print("d" in your_dict)

# 4. Change value of "a" to 4
your_dict["a"] = 4

# 5. Print dictionary again
print(your_dict)    